function q(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sql() {
  const ids = new Set(exercises.map((e) => e.id));
  const programIds = new Set(programs.map((p) => p.id));
  const lines = [
    "-- Generated by scripts/catalog-data.mjs. Re-run that script to regenerate.",
  ];
  for (const e of exercises) {
    lines.push(
      `insert into exercises (id, slug, name, description, target_muscles, equipment, difficulty, premium, video_url, thumbnail_url, instructions, mistakes, beginner_mod, advanced_mod, default_sets, default_reps, default_seconds, rest_seconds, calories_per_min) values (${q(e.id)}, ${q(e.id)}, ${q(e.name)}, ${q(e.description)}, ${q(JSON.stringify(e.muscles))}, ${q(e.equipment)}, ${q(e.difficulty)}, ${e.premium ? "true" : "false"}, null, ${q(e.thumb)}, ${q(JSON.stringify(e.steps))}, ${q(JSON.stringify(e.mistakes))}, ${q(e.beginner)}, ${q(e.advanced)}, ${e.sets}, ${e.reps ?? "null"}, ${e.seconds ?? "null"}, ${e.rest}, ${e.cal}) on conflict (id) do nothing;`,
    );
  }
  for (const p of programs) {
    lines.push(
      `insert into programs (id, slug, title, description, goal_key, difficulty, duration_days, equipment, requires, cover_image, premium, sort_order) values (${q(p.id)}, ${q(p.id)}, ${q(p.title)}, ${q(p.description)}, ${q(p.goalKey)}, ${q(p.difficulty)}, ${p.durationDays}, ${q(p.equipment)}, ${q(p.requires)}, ${q(p.cover)}, ${p.premium ? "true" : "false"}, ${p.sort}) on conflict (id) do nothing;`,
    );
  }
  for (const w of workouts) {
    if (!programIds.has(w.programId)) throw new Error(`missing program ${w.programId}`);
    const premium = programs.find((p) => p.id === w.programId)?.premium;
    const preview = Boolean(premium && w.day === 1);
    const id = `${w.programId}-d${w.day}`;
    lines.push(
      `insert into workouts (id, program_id, day_index, title, description, duration_min, difficulty, goal, equipment, base_calories, free_preview) values (${q(id)}, ${q(w.programId)}, ${w.day}, ${q(w.title)}, ${q(w.description)}, ${w.minutes}, ${q(w.difficulty)}, ${q(w.goal)}, ${q(w.equipment)}, ${w.calories}, ${preview ? "true" : "false"}) on conflict (id) do nothing;`,
    );
    w.items.forEach((item, index) => {
      const [exerciseId, sets, reps, seconds, rest] = item;
      if (!ids.has(exerciseId)) throw new Error(`missing exercise ${exerciseId} in ${id}`);
      lines.push(
        `insert into workout_exercises (workout_id, exercise_id, position, sets, reps, seconds, rest_seconds) values (${q(id)}, ${q(exerciseId)}, ${index + 1}, ${sets}, ${reps ?? "null"}, ${seconds ?? "null"}, ${rest}) on conflict (workout_id, position) do nothing;`,
      );
    });
  }
  return lines.join("\n") + "\n";
}

const out = new URL("../migrations/0003_seed.sql", import.meta.url);
writeFileSync(out, sql());
console.log(`wrote ${out.pathname} (${workouts.length} workouts, ${exercises.length} exercises)`);
